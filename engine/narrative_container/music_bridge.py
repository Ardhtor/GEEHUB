"""Bridge music-derived cues into the narrative correspondence ledger.

A cue sheet can be authored by a person or generated by an audio-analysis adapter.
The bridge preserves the cue's track/time provenance and writes each cue as a
normal narrative artifact. Audio analysis and playback are intentionally separate.
"""
from __future__ import annotations

from typing import Any

from .music_program import load_program
from .ledger import Ledger


def transmit_music_window(
    ledger: Ledger,
    track_manifest: dict[str, Any],
    after_ms: int,
    through_ms: int,
    sender: str,
    source_narrative: str,
    recipient: str,
    destination_narrative: str,
) -> list[str]:
    program = load_program(track_manifest)
    created: list[str] = []
    for event in program.events_until(through_ms, after_ms):
        artifact_id = event["event_id"].replace(":", "-")
        payload = {
            "instruction": event["instruction"],
            "intensity": event["intensity"],
            "section": event["section"],
            "target": event["target"],
            "music_position_ms": event["at_ms"],
            "acoustic_profile": event.get("acoustic_profile"),
        }
        ledger.add({
            "id": artifact_id,
            "kind": "music_event" if event.get("acoustic_profile") else "text",
            "sender": sender,
            "source": source_narrative,
            "recipient": recipient,
            "destination": destination_narrative,
            "version": 1,
            "context": "Music-program event; track=" + event["track_id"],
            "payload": payload,
            "status": "sent",
        })
        created.append(artifact_id)
    return created
